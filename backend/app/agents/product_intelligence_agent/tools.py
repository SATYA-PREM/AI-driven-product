"""
tools.py
--------
Controlled tools for Agent 3 (Product Intelligence Agent).
"""

from __future__ import annotations

from typing import Any
from app.repositories.intelligence_repository import intelligence_repository
from app.services.intelligence.scoring_service import scoring_service
from app.services.ai.response_parser import response_parser
from app.schemas.intelligence import ProductInsightOutput


try:
    from crewai.tools import tool as crewai_tool
except ImportError:
    def crewai_tool(name_or_func=None, **kwargs):
        def decorator(f):
            return f
        if callable(name_or_func):
            return name_or_func
        return decorator


def get_issue_clusters(workspace_id: str, dataset_id: str | None = None) -> list[dict[str, Any]]:
    """Retrieve issue clusters generated by Agent 2."""
    return intelligence_repository.get_issue_clusters(workspace_id, dataset_id)


get_issue_clusters_tool = crewai_tool("get_issue_clusters")(get_issue_clusters)


def get_feature_clusters(workspace_id: str, dataset_id: str | None = None) -> list[dict[str, Any]]:
    """Retrieve feature clusters generated by Agent 2."""
    return intelligence_repository.get_feature_clusters(workspace_id, dataset_id)


get_feature_clusters_tool = crewai_tool("get_feature_clusters")(get_feature_clusters)


def get_trends(workspace_id: str, dataset_id: str | None = None) -> list[dict[str, Any]]:
    """Retrieve trends generated by Agent 2."""
    return intelligence_repository.get_trends(workspace_id, dataset_id)


get_trends_tool = crewai_tool("get_trends")(get_trends)


def calculate_priority_score(
    frequency: int,
    total_records: int,
    severity: str,
    trend_direction: str,
    trend_percentage: float,
    negative_ratio: float,
    customer_impact: str,
) -> tuple[float, str]:
    """Calculate deterministic priority score (0-100) and priority level."""
    return scoring_service.calculate_priority_score(
        frequency=frequency,
        total_records=total_records,
        severity=severity,
        trend_direction=trend_direction,
        trend_percentage=trend_percentage,
        negative_ratio=negative_ratio,
        customer_impact=customer_impact,
    )


@crewai_tool("calculate_priority_score_tool")
def calculate_priority_score_tool(
    frequency: int,
    total_records: int,
    severity: str,
    trend_direction: str,
    trend_percentage: float,
    negative_ratio: float,
    customer_impact: str,
) -> dict[str, Any]:
    """Calculate deterministic priority score (0-100) and priority level for CrewAI."""
    score, level = scoring_service.calculate_priority_score(
        frequency=frequency,
        total_records=total_records,
        severity=severity,
        trend_direction=trend_direction,
        trend_percentage=trend_percentage,
        negative_ratio=negative_ratio,
        customer_impact=customer_impact,
    )
    return {"priority_score": score, "priority_level": level}


def validate_product_insight(insight_data: dict[str, Any]) -> tuple[bool, ProductInsightOutput | None, list[str]]:
    """Validate generated product insight against Pydantic schema."""
    return response_parser.validate_product_insight(insight_data)


@crewai_tool("validate_product_insight_tool")
def validate_product_insight_tool(insight_data: dict[str, Any]) -> dict[str, Any]:
    """Validate generated product insight against Pydantic schema for CrewAI."""
    is_valid, parsed, errors = response_parser.validate_product_insight(insight_data)
    return {
        "is_valid": is_valid,
        "errors": errors,
        "validated_insight": parsed.model_dump() if parsed else None,
    }


def save_product_insight(insight_data: dict[str, Any]) -> str:
    """Save a validated product insight to MongoDB."""
    return intelligence_repository.save_product_insight(insight_data)


save_product_insight_tool = crewai_tool("save_product_insight")(save_product_insight)


def save_product_insights(insights_data: list[dict[str, Any]]) -> int:
    """Save multiple validated product insights to MongoDB using bulk write."""
    return intelligence_repository.save_product_insights(insights_data)


save_product_insights_tool = crewai_tool("save_product_insights")(save_product_insights)



