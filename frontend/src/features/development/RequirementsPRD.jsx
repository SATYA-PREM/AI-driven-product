function cn(...classes) {
  return classes.filter(Boolean).join(';');
}

function StatusBadge({ value }) {
  const map = {
    'Validated': 'bg-green-500/10 text-green-400 border-green-500/20',
    'Pending Validation': 'bg-yellow-500/10 text-yellow-400 border-yellow-500/20',
    'Shared': 'bg-blue-500/10 text-blue-400 border-blue-500/20',
    'Draft': 'bg-slate-700/30 text-slate-400 border-slate-600/30',
  };
  return <span className={cn('inline-flex border rounded-md px-2 py-0.5 text-[9px] font-semibold', map[value] || 'bg-slate-800 text-slate-300')}>{value}</span>;
}

